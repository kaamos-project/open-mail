// `flutter build/run --dart-define=K=V` reaches Gradle as the property
// "dart-defines": a comma-separated list of base64-encoded "K=V".
val dartDefines: Map<String, String> =
    (project.findProperty("dart-defines") as String?)
        ?.split(",")
        ?.filter { it.isNotEmpty() }
        ?.map { String(Base64.getDecoder().decode(it)) }
        ?.mapNotNull { entry ->
            val parts = entry.split("=", limit = 2)
            if (parts.size == 2) parts[0] to parts[1] else null
        }
        ?.toMap()
        ?: emptyMap()

// Google's redirect scheme is the Android client ID reversed, like
// `googleAppRedirect` in lib/src/core/oauth.dart. Without a client ID the
// filter just repeats the Microsoft scheme.
val googleRedirectScheme: String =
    dartDefines["KAAMOS_GOOGLE_ANDROID_CLIENT_ID"]
        ?.takeIf { it.endsWith(".apps.googleusercontent.com") }
        ?.removeSuffix(".apps.googleusercontent.com")
        ?.let { "com.googleusercontent.apps.$it" }
        ?: "dev.kaamos-project.mail"

